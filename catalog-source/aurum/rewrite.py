def pick(table, text):
    t = norm(text)
    for k, v in table.items():
        if t.startswith(norm(k)):
            return v
    return None


d = json.load(open(PATH, encoding='utf-8'))
n = 0
for p in d['products']:
    new = pick(DESC, p.get('desc', ''))
    if new and new != p['desc']:
        p['desc'] = new; n += 1
    for s in p.get('specs', []):
        new = pick(SPECS, s['value'])
        if new and new != s['value']:
            s['value'] = new; n += 1
for c in d['categories']:
    if c['slug'] in LEADS and c['lead'] != LEADS[c['slug']]:
        c['lead'] = LEADS[c['slug']]; n += 1
json.dump(d, open(PATH, 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
