def get(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': UA}), timeout=40).read()


def webp(url, rel, box):
    out = os.path.join(SITE, rel)
    if not os.path.exists(out):
        im = Image.open(io.BytesIO(get(url)))
        im = im.convert('RGB')
        im.thumbnail(box, Image.LANCZOS)
        os.makedirs(os.path.dirname(out), exist_ok=True)
        im.save(out, 'WEBP', quality=80, method=6)
    return rel


def blocks(descr):
    """Текст всплывающего окна → [{'h': подзаголовок} | {'p': абзац}]. Жирная строка в начале абзаца — подзаголовок."""
    s = str(descr)
    s = re.sub(r'^<div[^>]*>|</div>$', '', s.strip())
    s = re.sub(r'(?i)<br\s*/?>', '\n', s)
    s = s.replace('﻿', '')
    out = []
    for chunk in re.split(r'\n\s*\n', s):
        lines = [l.strip() for l in chunk.split('\n') if l.strip()]
        for l in lines:
            m = re.match(r'^<(strong|b)>(.*?)</\1>$', l)
            text = H.unescape(re.sub(r'<[^>]+>', '', l)).strip()
            text = re.sub(r'\s+', ' ', text)
            if not text:
                continue
            if m:
                out.append({'h': text})
            else:
                out.append({'p': text})
    return out


def main(path):
    soup = BeautifulSoup(open(path, encoding='utf-8').read(), 'html.parser')
    videos = []
    for i, (vid, title) in enumerate(RUTUBE):
        info = json.loads(get('https://rutube.ru/api/video/%s/?format=json' % vid))
        videos.append({'id': vid, 'title': title, 'duration': info.get('duration') or 0,
                       'poster': webp(info['thumbnail_url'], 'img/gid/rt-%d.webp' % (i + 1), (1280, 720))})
    tech = []
    for hook, slug, title in TECH:
        p = soup.find(attrs={'data-tooltip-hook': hook})
        img = p.select_one('img.t390__img')
        src = img.get('data-original') or img.get('src')
        txt = TECH_TEXT[slug]
        tech.append({'slug': slug, 'title': title, 'img': webp(src, 'img/gid/tech-%s.webp' % slug, (1200, 1200)),
                     'lead': txt['lead'], 'points': [{'t': a, 'd': b} for a, b in txt['points']]})
    json.dump({'videos': videos, 'tech': tech}, open(os.path.join(SITE, 'data', 'gid.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    for v in videos:
        print(v['title'], v['duration'])
    for t in tech:
        print(t['title'], len(t['points']))


main(sys.argv[1])
